"""Train the risk model from the exported CSV, save it, and write the results report.

Reproducible: the same CSV gives the same model (fixed random seeds, time-based split).

Run from the project root:
  python -m scripts.train_risk_model                          # data/risk_dataset.csv
  python -m scripts.train_risk_model data/risk_dataset.csv --version risk-model-v2
"""
import argparse
from pathlib import Path

import joblib

from app.modules.ml.features import MODEL_FEATURES
from app.modules.ml.training import (
  FALSE_NEGATIVE_COST,
  FALSE_POSITIVE_COST,
  TrainingResult,
  bundle,
  load_csv,
  train,
)


def report(result: TrainingResult, version: str, dataset_path: Path) -> str:
  def table(header: list[str], rows: list[list[str]]) -> list[str]:
    return [
      "| " + " | ".join(header) + " |",
      "|" + "---|" * len(header),
      *("| " + " | ".join(row) + " |" for row in rows),
    ]

  lines = [
    f"# Risk model results ({version})",
    "",
    f"Generated by `python -m scripts.train_risk_model {dataset_path}`. Do not edit by hand.",
    "",
    f"- Rows: {result.train_rows} train, {result.test_rows} test (newest PRs).",
    f"- Closed without merge: {result.positive_share:.1%} of all rows.",
    f"- Chosen model: {result.model_name}, sigmoid-calibrated, threshold {result.threshold:.2f} "
    f"(a missed rejection costs {FALSE_NEGATIVE_COST:g}, a false alarm {FALSE_POSITIVE_COST:g}).",
    "",
    "## Test set",
    "",
    *table(
      ["Model", "ROC-AUC", "PR-AUC", "Precision", "Recall", "Precision, top 10%"],
      [[name, *metrics.as_row()] for name, metrics in result.test_metrics.items()],
    ),
    "",
    "Raw models are evaluated at 0.5; the rule score and lines-only baselines at a threshold chosen",
    "on the calibration part of the training set, like the chosen model.",
    "",
    "## Cross-validation (training set, time-ordered folds)",
    "",
    *table(["Model", "PR-AUC"], [[name, f"{score:.3f}"] for name, score in result.cv_pr_auc.items()]),
    "",
    "## By segment (test set, chosen model)",
    "",
    *table(
      ["Segment", "ROC-AUC", "PR-AUC", "Precision", "Recall", "Precision, top 10%"],
      [[name, *metrics.as_row()] for name, metrics in result.segments.items()],
    ),
    "",
    "## What the models learned",
    "",
    *table(
      ["Feature", "Logistic regression coefficient (scaled)", "Permutation importance (PR-AUC drop)"],
      [
        [name, f"{result.coefficients[name]:+.3f}", f"{result.importances[name]:+.4f}"]
        for name in MODEL_FEATURES
      ],
    ),
    "",
    "## Calibration (test set)",
    "",
    *table(
      ["Mean predicted", "Observed rejected", "PRs"],
      [[f"{p:.2f}", f"{o:.2f}", str(c)] for p, o, c in result.reliability],
    ),
    "",
    "## The 10 most confident mistakes (test set)",
    "",
    *table(
      ["PR id", "Repository", "Probability", "Actual", "Lines (log)", "Files (log)", "Author prior PRs (log)"],
      [
        [
          str(miss["pull_request_id"]),
          miss["repository"],
          f"{miss['probability']:.2f}",
          miss["actual"],
          f"{miss['log_lines_changed']:.1f}",
          f"{miss['log_files_changed']:.1f}",
          f"{miss['log_author_prior_prs']:.1f}",
        ]
        for miss in result.worst_misses
      ],
    ),
    "",
  ]
  return "\n".join(lines)


def main() -> None:
  parser = argparse.ArgumentParser(description="Train the PR risk model.")
  parser.add_argument("dataset", nargs="?", type=Path, default=Path("data/risk_dataset.csv"))
  parser.add_argument("--version", default="risk-model-v1")
  parser.add_argument("--model-out", type=Path, default=Path("models/risk_model.joblib"))
  parser.add_argument("--report-out", type=Path, default=Path("doc/ml-results.md"))
  args = parser.parse_args()

  dataset = load_csv(args.dataset)
  result = train(dataset)

  args.model_out.parent.mkdir(parents=True, exist_ok=True)
  joblib.dump(bundle(result, dataset, args.version), args.model_out)
  args.report_out.write_text(report(result, args.version, args.dataset))

  chosen = list(result.test_metrics.values())[-1]
  rules = result.test_metrics["Rule score (rules-v1)"]
  print(f"Saved {args.model_out} ({result.model_name}, threshold {result.threshold:.2f})")
  print(f"Test PR-AUC: model {chosen.as_row()[1]} vs rule score {rules.as_row()[1]}")
  print(f"Report: {args.report_out}")


if __name__ == "__main__":
  main()
