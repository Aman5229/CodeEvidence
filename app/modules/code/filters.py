"""Which files are worth reading, and in which language they are written.

Lock files, vendored and generated code, and binaries are skipped: nobody reviews them line
by line, and they would crowd out real code in the retrieval index and the review prompt.
"""

from pathlib import PurePosixPath

MAX_FILE_BYTES = 200_000  # larger files are almost always data or generated

LANGUAGES = {
  ".py": "python",
  ".js": "javascript",
  ".jsx": "javascript",
  ".mjs": "javascript",
  ".cjs": "javascript",
  ".ts": "typescript",
  ".tsx": "typescript",
  ".rb": "ruby",
  ".go": "go",
  ".java": "java",
  ".kt": "kotlin",
  ".rs": "rust",
  ".php": "php",
  ".cs": "csharp",
  ".c": "c",
  ".h": "c",
  ".cpp": "cpp",
  ".swift": "swift",
  ".scala": "scala",
  ".sh": "shell",
  ".sql": "sql",
}

LOCK_FILES = {
  "package-lock.json",
  "yarn.lock",
  "pnpm-lock.yaml",
  "poetry.lock",
  "pipfile.lock",
  "uv.lock",
  "pdm.lock",
  "cargo.lock",
  "gemfile.lock",
  "composer.lock",
  "go.sum",
}
VENDORED_FOLDERS = {"vendor", "vendors", "node_modules", "third_party", "dist", "build", "site-packages", "__pycache__", ".git"}
GENERATED_SUFFIXES = (".min.js", ".min.css", "_pb2.py", "_pb2_grpc.py", ".pb.go", ".map", ".snap")
BINARY_EXTENSIONS = {
  ".png", ".jpg", ".jpeg", ".gif", ".ico", ".webp", ".bmp", ".pdf", ".zip", ".gz", ".tar", ".tgz",
  ".woff", ".woff2", ".ttf", ".eot", ".otf", ".mp3", ".mp4", ".mov", ".so", ".dylib", ".dll",
  ".exe", ".jar", ".class", ".pyc", ".whl", ".db", ".sqlite",
}
GENERATED_MARKERS = ("@generated", "do not edit", "auto-generated", "autogenerated")


def skip_reason(path: str) -> str | None:
  """Why a file is not worth reviewing (lock_file, vendored, generated, binary), or None."""
  file = PurePosixPath(path.lower())
  if file.name in LOCK_FILES:
    return "lock_file"
  if any(part in VENDORED_FOLDERS for part in file.parts[:-1]):
    return "vendored"
  if file.name.endswith(GENERATED_SUFFIXES):
    return "generated"
  if file.suffix in BINARY_EXTENSIONS:
    return "binary"
  return None


def looks_generated(content: str) -> bool:
  """Generated files usually say so in their first lines."""
  head = "\n".join(content.splitlines()[:5]).lower()
  return any(marker in head for marker in GENERATED_MARKERS)


def detect_language(path: str) -> str | None:
  return LANGUAGES.get(PurePosixPath(path.lower()).suffix)
