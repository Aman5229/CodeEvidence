# A real-shaped GitHub patch: two hunks, an added line at the end without a newline marker
PATCH = """@@ -3,6 +3,7 @@ import os

 def load(path):
-    with open(path) as f:
+    with open(path, encoding="utf-8") as f:
+        # read everything
         return f.read()


@@ -40,3 +41,2 @@ def save(path, data):
     with open(path, "w") as f:
-        f.write(data)
-        f.flush()
+        f.write(data)
\\ No newline at end of file"""


# ---------- diff ----------

def test_hunk_headers_and_line_numbers():
  first, second = parse_patch(PATCH)

  assert (first.old_start, first.old_count, first.new_start, first.new_count) == (3, 6, 3, 7)
  assert first.section == "import os"
  assert [(line.new_line, line.text.strip()) for line in first.added] == [
    (5, 'with open(path, encoding="utf-8") as f:'),
    (6, "# read everything"),
  ]
  assert [line.old_line for line in first.removed] == [5]
  assert second.new_start == 41
  assert [line.new_line for line in second.added] == [42]
  assert [line.old_line for line in second.removed] == [41, 42]


def test_context_lines_have_both_numbers():
  first = parse_patch(PATCH)[0]
  context = [line for line in first.lines if line.kind == "context"]

  assert (context[0].old_line, context[0].new_line) == (3, 3)
  assert (context[2].old_line, context[2].new_line) == (6, 7)  # shifted by the added line


def test_no_newline_marker_is_ignored_and_text_round_trips():
  second = parse_patch(PATCH)[1]

  assert all("No newline" not in line.text for line in second.lines)
  assert parse_patch(second.text())[0].added == second.added


@pytest.mark.parametrize("patch", [None, "", "Binary files differ"])
def test_missing_or_binary_patch_has_no_hunks(patch):
  assert parse_patch(patch) == []


def test_single_line_hunk_without_counts():
  (hunk,) = parse_patch("@@ -1 +1 @@\n-old\n+new")

  assert (hunk.old_count, hunk.new_count) == (1, 1)
  assert hunk.new_lines == {1}


