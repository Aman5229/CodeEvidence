# ---------- chunking ----------

PYTHON = '''import os


@cache
def load(path):
    return open(path).read()


class Store:
    def get(self, key):
        return self.data[key]

    def put(self, key, value):
        self.data[key] = value
'''

JAVASCRIPT = '''export function add(a, b) {
  return a + b
}

const double = (x) => x * 2

class Counter {
  increment() { this.n += 1 }
}
'''


def test_python_is_chunked_by_function_and_class():
  chunks = chunk_file("app/store.py", PYTHON, "python")

  assert [(c.kind, c.name, c.start_line, c.end_line) for c in chunks] == [
    ("function", "load", 4, 6),  # the decorator is part of the chunk
    ("class", "Store", 9, 14),
  ]
  assert chunks[0].content.startswith("@cache")


def test_javascript_functions_arrows_and_classes():
  chunks = chunk_file("src/math.js", JAVASCRIPT, "javascript")

  assert [(c.kind, c.name) for c in chunks] == [("function", "add"), ("function", "double"), ("class", "Counter")]


def test_large_class_is_split_into_methods():
  body = "\n".join(f"        x{i} = {i}" for i in range(MAX_CHUNK_LINES))
  source = f"class Big:\n    def first(self):\n{body}\n\n    def second(self):\n        return 2\n"

  chunks = chunk_file("big.py", source, "python")

  names = [c.name for c in chunks]
  assert "Big.second" in names
  assert all(c.kind == "method" for c in chunks)
  assert names.count("Big.first") >= 2  # too long for one chunk: split into windows


def test_other_languages_and_scripts_fall_back_to_windows():
  source = "\n".join(f"line {i}" for i in range(WINDOW_LINES + 20))

  chunks = chunk_file("script.rb", source, "ruby")

  assert [c.kind for c in chunks] == ["window", "window"]
  assert chunks[0].end_line == WINDOW_LINES
  assert chunks[1].start_line < chunks[0].end_line  # windows overlap
  assert chunks[-1].end_line == WINDOW_LINES + 20


def test_empty_file_has_no_chunks():
  assert chunk_file("empty.py", "", "python") == []
